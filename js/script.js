const form = document.getElementById("contactForm");
const formMessage = document.getElementById("formMessage");

form.addEventListener("submit", async event => {

    event.preventDefault();

    const lang = document.documentElement.lang || "de";
    const dict = translations[lang];

    if (!form.checkValidity()) {
        form.reportValidity();
        formMessage.textContent = dict.formRequired;
        return;
    }

    const submitButton = form.querySelector('button[type="submit"]');
    const originalButtonHTML = submitButton ? submitButton.innerHTML : "";

    if (submitButton) {
        submitButton.disabled = true;
        submitButton.innerHTML = '<span>...</span>';
    }

    formMessage.textContent = "";

    try {
        const response = await fetch("/api/contact", {
            method: "POST",
            headers: { "Content-Type": "application/json" },
            body: JSON.stringify({
                vorname: form.elements.vorname.value.trim(),
                nachname: form.elements.nachname.value.trim(),
                email: form.elements.email.value.trim(),
                telefon: form.elements.telefon.value.trim(),
                nachricht: form.elements.nachricht.value.trim(),
                language: lang
            })
        });

        const result = await response.json();
        if (!response.ok) throw new Error(result.error || "SEND_FAILED");

        formMessage.textContent = dict.formSuccess;
        form.reset();
    } catch (error) {
        console.error("Contact form error:", error);
        formMessage.textContent =
            lang === "fr" ? "Une erreur est survenue. Veuillez réessayer." :
            lang === "en" ? "Something went wrong. Please try again." :
            lang === "ar" ? "حدث خطأ. يرجى المحاولة مرة أخرى." :
            "Es ist ein Fehler aufgetreten. Bitte versuche es erneut.";
    } finally {
        if (submitButton) {
            submitButton.disabled = false;
            submitButton.innerHTML = originalButtonHTML;
        }
    }
});


