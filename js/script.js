/* ================= LANGUAGE ================= */

const languageSwitcher = document.getElementById("languageSwitcher");
const languageButton = document.getElementById("languageButton");
const languageMenu = document.getElementById("languageMenu");
const currentLanguage = document.getElementById("currentLanguage");
const currentFlag = document.getElementById("currentFlag");

const flagCodes = {
    de: "de",
    fr: "fr",
    en: "gb",
    ar: "ma"
};

function applyLanguage(lang) {

    const dict = translations[lang] || translations.de;

    document.documentElement.lang = lang;
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";

    document.title = dict.pageTitle;

    const meta = document.querySelector('meta[name="description"]');
    if (meta) {
        meta.setAttribute("content", dict.metaDescription);
    }

    /* Normal text / HTML */
    document.querySelectorAll("[data-i18n]").forEach(element => {
        const key = element.dataset.i18n;

        if (dict[key] !== undefined) {
            element.innerHTML = dict[key];
        }
    });

    document.querySelectorAll("[data-i18n-html]").forEach(element => {
        const key = element.dataset.i18nHtml;

        if (dict[key] !== undefined) {
            element.innerHTML = dict[key];
        }
    });

    /* Placeholders */
    document.querySelectorAll("[data-i18n-placeholder]").forEach(element => {
        const key = element.dataset.i18nPlaceholder;

        if (dict[key] !== undefined) {
            element.placeholder = dict[key];
        }
    });

    /* Current language + flag */
    currentLanguage.textContent = lang.toUpperCase();

    currentFlag.className = `fi fi-${flagCodes[lang]} language-flag`;

    /* Active option */
    document.querySelectorAll(".language-option").forEach(option => {
        option.classList.toggle("active", option.dataset.lang === lang);
    });

    /* Copyright year */
    const copyright = document.querySelector("[data-i18n='copyright']");
    if (copyright && dict.copyright) {
        copyright.innerHTML = dict.copyright.replace(
            "{year}",
            new Date().getFullYear()
        );
    }

    /* Save language */
    localStorage.setItem("alphadeutsch-language", lang);
}


/* Open / close dropdown */

languageButton.addEventListener("click", event => {
    event.stopPropagation();

    const isOpen = languageMenu.classList.toggle("open");

    languageButton.setAttribute(
        "aria-expanded",
        String(isOpen)
    );
});


/* Choose language */

document.querySelectorAll(".language-option").forEach(option => {

    option.addEventListener("click", () => {

        const lang = option.dataset.lang;

        applyLanguage(lang);

        languageMenu.classList.remove("open");
        languageButton.setAttribute("aria-expanded", "false");
    });

});


/* Close when clicking outside */

document.addEventListener("click", event => {

    if (!languageSwitcher.contains(event.target)) {
        languageMenu.classList.remove("open");
        languageButton.setAttribute("aria-expanded", "false");
    }

});


/* ================= MOBILE MENU ================= */

const menuToggle = document.getElementById("menuToggle");
const navLinks = document.getElementById("navLinks");

menuToggle.addEventListener("click", () => {

    const isOpen = navLinks.classList.toggle("open");

    menuToggle.setAttribute(
        "aria-expanded",
        String(isOpen)
    );

});


/* Close mobile menu after clicking a link */

document.querySelectorAll('.nav-links a[href^="#"]').forEach(link => {

    link.addEventListener("click", () => {

        navLinks.classList.remove("open");
        menuToggle.setAttribute("aria-expanded", "false");

    });

});


/* ================= ACTIVE NAV ================= */

const sections = document.querySelectorAll("main section[id]");
const navItems = document.querySelectorAll('.nav-links a[href^="#"]');

const observer = new IntersectionObserver(
    entries => {

        entries.forEach(entry => {

            if (!entry.isIntersecting) return;

            navItems.forEach(item => {
                item.classList.remove("active");
            });

            const activeLink = document.querySelector(
                `.nav-links a[href="#${entry.target.id}"]`
            );

            if (activeLink) {
                activeLink.classList.add("active");
            }

        });

    },
    {
        rootMargin: "-35% 0px -55% 0px"
    }
);

sections.forEach(section => {
    observer.observe(section);
});


/* ================= COUNTERS ================= */

const counters = document.querySelectorAll("[data-count]");

const counterObserver = new IntersectionObserver(
    entries => {

        entries.forEach(entry => {

            if (!entry.isIntersecting) return;

            const element = entry.target;
            const target = Number(element.dataset.count);
            const prefix = element.dataset.prefix || "";

            const duration = 1300;
            const start = performance.now();

            function animate(now) {

                const progress = Math.min(
                    (now - start) / duration,
                    1
                );

                const eased = 1 - Math.pow(1 - progress, 3);

                element.textContent =
                    prefix + Math.floor(target * eased);

                if (progress < 1) {
                    requestAnimationFrame(animate);
                } else {
                    element.textContent = prefix + target;
                }
            }

            requestAnimationFrame(animate);

            counterObserver.unobserve(element);
        });

    },
    {
        threshold: .4
    }
);

counters.forEach(counter => {
    counterObserver.observe(counter);
});

